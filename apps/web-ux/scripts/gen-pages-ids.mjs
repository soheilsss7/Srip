/* ============================================================================
   gen-pages-ids.mjs — extracts all entity ids from mock-api.mjs and writes
   app/_lib/pages-ids.ts so every dynamic route ([id]) can export
   generateStaticParams() for the static GitHub Pages export.
   ============================================================================ */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(__dirname, 'mock-api.mjs'), 'utf8');
const outPath = path.join(__dirname, '..', 'app', '_lib', 'pages-ids.ts');

const ARRAYS = [
  ['organizations', 'let ORGS'],
  ['people', 'let PEOPLE'],
  ['relationships', 'let RELS'],
  ['meetings', 'let MEETINGS'],
  ['actions', 'let ACTIONS'],
  ['commitments', 'let COMMITMENTS'],
  ['projects', 'let PROJECTS'],
  ['opportunities', 'let OPPORTUNITIES'],
  ['interactions', 'let INTERACTIONS'],
  ['notifications', 'let NOTIFICATIONS'],
  ['recommendations', 'let RECS'],
];

const out = {};
for (const [key, anchor] of ARRAYS) {
  const start = src.indexOf(anchor);
  if (start < 0) { out[key] = []; continue; }
  const end = src.indexOf('];', start);
  const block = src.slice(start, end < 0 ? start + 4000 : end);
  const ids = [...block.matchAll(/id:\s*'([^']+)'/g)].map((m) => m[1]);
  out[key] = [...new Set(ids)];
}

const lines = [
  '// AUTO-GENERATED by scripts/gen-pages-ids.mjs — do not edit by hand.',
  '// Ids come from scripts/mock-api.mjs so every dynamic route can be',
  '// statically pre-rendered (GitHub Pages export, SRIP_PAGES=1).',
  'export const pageIds: Record<string, string[]> = {',
];
for (const [key, ids] of Object.entries(out)) {
  lines.push(`  ${key}: ${JSON.stringify(ids)},`);
}
lines.push('};');
fs.writeFileSync(outPath, lines.join('\n') + '\n');
console.log(`[gen-pages-ids] wrote ${outPath}`);
for (const [k, v] of Object.entries(out)) console.log(`  ${k}: ${v.length} ids`);
