def zwnj_escaped(s):
    return s.replace('\u200c', '\\u200c')

def apply_pairs(text, pairs, report, fname):
    for old, new in pairs:
        for o, n in ((old, new), (zwnj_escaped(old), zwnj_escaped(new))):
            if o == n:
                continue
            c = text.count(o)
            if c:
                text = text.replace(o, n)
                report.append(f'  {fname}: {c}× «{o[:58]}{"…" if len(o) > 58 else ""}»')
    return text

def main():
    phase = sys.argv[1] if len(sys.argv) > 1 else 'codes'
    pairs = []
    if phase == 'codes':
        pairs = REMOVED_CODE_PAIRS
    elif phase == 'sv14':
        pairs = SDV6_PAIRS
    elif phase == 'texts':
        pairs = TEXT_PAIRS
    else:
        sys.exit('فاز نامعتبر — از: codes | sv14 | texts')

    report = []
    for rel in FILES:
        p = ROOT / rel
        if not p.exists():
            print(f'!! فایل یافت نشد: {rel}')
            continue
        text = p.read_text(encoding='utf-8')
        orig = text
        text = apply_pairs(text, pairs, report, rel)
        if phase == 'codes':
            text = apply_pairs(text, GENERIC_RENUMBER, report, rel)
            text = apply_pairs(text, DOM_ATTRS, report, rel)
        if text != orig:
            p.write_text(text, encoding='utf-8')

    if report:
        print('\n'.join(report))
        print(f'\nمجموع: {len(report)} الگو-فایل اعمال شد (فاز {phase}).')
    else:
        print(f'هیچ جایگزینی در فاز {phase} اعمال نشد!')

    # ── راستی‌آزمایی فاز codes ──
    if phase == 'codes':
        leftovers = []
        for rel in FILES:
            p = ROOT / rel
            if not p.exists():
                continue
            text = p.read_text(encoding='utf-8')
            for m in re.finditer(r'F1[3-8]', text):
                start = max(0, m.start() - 30)
                snippet = text[start:m.end() + 30].replace('\n', '␤')
                leftovers.append(f'  {rel}: …{snippet}…')
        print('\n── باقی‌ماندهٔ F13–F18 (باید فقط F13_ACTIONS و ردیف‌های دستی کاتالوگ باشد) ──')
        seen = set()
        for l in leftovers:
            if l not in seen:
                seen.add(l)
                print(l)

if __name__ == '__main__':
    main()
